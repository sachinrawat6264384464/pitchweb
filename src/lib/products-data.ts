export function generateWhatsAppLink(productName?: string, price?: number, size?: string): string {
  const phone = STORE_INFO.whatsapp;
  let text = `Namaste Mayra Ethnic Indore! 🙏`;
  if (productName && price) {
    text += `\nMujhe aapka yeh product pasand aaya hai:\n📌 *${productName}*\n💰 Price: ₹${price.toLocaleString("en-IN")}`;
    if (size) {
      text += `\n📏 Size: ${size}`;
    }
    text += `\n\nKya yeh currently available hai? Store visit ya delivery details bataiye please.`;
  } else {
    text += `\nMain aapke collection aur latest designs ke baare me inquiry karna chahta hoon. Please catalog share karein.`;
  }
  return `https://wa.me/${phone}?text=${encodeURIComponent(text)}`;
}
